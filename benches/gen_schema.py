#!/usr/bin/env python3
"""Generate a synthetic Prisma schema with N models, for benchmarking `convert`.

The output is deterministic: the same N always produces the same file, so two
measurements made at different times run on identical input.

Each model has 12 fields covering the importer's common paths (ids, defaults,
@map, @db.* hints, optional fields, enums, arrays, timestamps), a relation to
the previous model, a @@map and two @@index. Every 10th model also gets a
compound unique constraint. A few enums are shared by all models.

Usage:
    python3 benches/gen_schema.py <n_models> > schema.prisma
"""

import sys

ENUMS = {
    "Status": ["DRAFT", "ACTIVE", "ARCHIVED"],
    "Priority": ["LOW", "MEDIUM", "HIGH", "CRITICAL"],
    "Region": ["EU", "US", "APAC"],
}


def model(i: int, n: int) -> str:
    name = f"Model{i}"
    enum_name = list(ENUMS)[i % len(ENUMS)]
    enum_default = ENUMS[enum_name][0]
    lines = [
        f"model {name} {{",
        "  id          Int       @id @default(autoincrement())",
        "  uuid        String    @unique @default(uuid()) @db.Uuid",
        "  title       String    @db.VarChar(255)",
        "  description String?   @db.Text",
        f"  kind        {enum_name:<9} @default({enum_default})",
        "  score       Int       @default(0) @db.SmallInt",
        "  amount      Decimal   @default(0) @db.Decimal(12, 2)",
        "  enabled     Boolean   @default(true)",
        "  tags        String[]",
        "  metadata    Json?     @db.JsonB",
        '  createdAt   DateTime  @default(now()) @map("created_at")',
        '  updatedAt   DateTime  @updatedAt @map("updated_at")',
    ]
    if i > 0:
        prev = f"Model{i - 1}"
        lines += [
            '  parentId    Int?      @map("parent_id")',
            "",
            f"  parent      {prev}? @relation(fields: [parentId], references: [id], onDelete: Cascade)",
        ]
    if i + 1 < n:
        # back-relation of the next model's `parent`
        lines.append(f"  children    Model{i + 1}[]")
    lines.append("")
    lines += [
        f'  @@map("model_{i}")',
        "  @@index([createdAt(sort: Desc)])",
        "  @@index([kind, score])",
    ]
    if i % 10 == 0:
        lines.append("  @@unique([title, kind])")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 2 or not sys.argv[1].isdigit() or int(sys.argv[1]) < 1:
        sys.exit("usage: gen_schema.py <n_models>  (n_models >= 1)")
    n = int(sys.argv[1])

    out = [
        f"// Synthetic benchmark schema: {n} models. Generated by benches/gen_schema.py.",
        "",
        "datasource db {",
        '  provider = "postgresql"',
        '  url      = env("DATABASE_URL")',
        "}",
        "",
        "generator client {",
        '  provider = "prisma-client-js"',
        "}",
        "",
    ]
    for enum_name, values in ENUMS.items():
        out.append(f"enum {enum_name} {{")
        out += [f"  {v}" for v in values]
        out += ["}", ""]
    for i in range(n):
        out += [model(i, n), ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
